"""
Compute the 9 observables on multi-L cross-L samples at L=128 and compare
with HMC at L=128 for kappa in {0.26, 0.2705, 0.28}.

Inputs:
  runs/phi4_Lmulti8-16-32-64_k{K}_l0.022_ncsnpp/data_crossL/
        samples_multiL_L128_n1024.npy   (saved by sample_phi4_crossL.py)
  trainingdata/cfgs_wolff_fahmc_k={K}_l=0.022_128^2.jld2  (HMC reference)

Outputs:
  runs/_multiL_crossL_logs/multiL_crossL_L128.txt
  runs/_multiL_crossL_logs/multiL_crossL_L128.tex
"""

import json
import os
import sys

import h5py
import numpy as np

sys.path.insert(0, "/home/tyywork/DM/2Dphi4")
from analyze_diagnostic_observables import (
    block_jackknife, z2_augment, fmt_err, TEX_NAMES,
)

BASE = "/home/tyywork/DM/2Dphi4"
# (kappa_str, run_dir, training-data norm_min, norm_max, hmc_path)
KAPPAS = [
    ("0.26",
     "phi4_Lmulti8-16-32-64_k0.26_l0.022_ncsnpp",
     -4.205986499786377, 4.041594505310059,
     "trainingdata/cfgs_wolff_fahmc_k=0.26_l=0.022_128^2.jld2"),
    ("0.2705",
     "phi4_Lmulti8-16-32-64_k0.2705_l0.022_ncsnpp",
     -4.352510452270508, 4.3837151527404785,
     "trainingdata/cfgs_wolff_fahmc_k=0.2705_l=0.022_128^2.jld2"),
    ("0.28",
     "phi4_Lmulti8-16-32-64_k0.28_l0.022_ncsnpp",
     -4.778076171875, 4.771599292755127,
     "trainingdata/cfgs_wolff_fahmc_k=0.28_l=0.022_128^2.jld2"),
]
SAMPLE_TAG = "multiL_L128_n1024"
ORDER = ["abs_phi_bar","chi","U4","abs_phi","kappa2_s","kappa4_s","kappa6_s","kappa8_s","U4_s"]


def load_dm(rdir):
    f = os.path.join(BASE, "runs", rdir, "data_crossL", f"samples_{SAMPLE_TAG}.npy")
    x = np.load(f)  # (L, L, N)
    x = np.transpose(x, (2, 0, 1))
    return x.reshape(x.shape[0], -1).astype(np.float64), x.shape[1]


def load_hmc(path):
    with h5py.File(os.path.join(BASE, path), "r") as fh:
        cfgs = np.array(fh["cfgs"], dtype=np.float64)
    return cfgs.reshape(cfgs.shape[0], -1), cfgs.shape[1]


def fmt_sci(x, prec=1):
    if x == 0 or not np.isfinite(x):
        return f"{x:g}"
    if abs(x) >= 1e-2 and abs(x) < 1e3:
        return f"{x:.{prec+1}g}"
    exp = int(np.floor(np.log10(abs(x))))
    mant = x / 10**exp
    return f"{mant:.{prec}f}\\!\\times\\!10^{{{exp}}}"


def main():
    rows = []
    for k_str, rdir, nmin, nmax, hmc_path in KAPPAS:
        print(f"\n=== kappa = {k_str} ===")
        x_dm, L = load_dm(rdir)
        n_total = x_dm.shape[0]
        keep = (x_dm.min(axis=1) >= nmin) & (x_dm.max(axis=1) <= nmax)
        x_dm = x_dm[keep]
        n_kept = x_dm.shape[0]
        print(f"  DM: N_total={n_total}  N_kept={n_kept}  filter [{nmin:.3f},{nmax:.3f}]")
        x_dm_z2 = z2_augment(x_dm)
        dm_vals, dm_errs = block_jackknife(x_dm_z2, L, n_blocks=32)

        x_hmc, L_h = load_hmc(hmc_path)
        x_hmc_z2 = z2_augment(x_hmc)
        hmc_vals, hmc_errs = block_jackknife(x_hmc_z2, L_h, n_blocks=32)
        print(f"  HMC: N={x_hmc.shape[0]}")

        for obs in ORDER:
            dv, de = dm_vals[obs], dm_errs[obs]
            hv, he = hmc_vals[obs], hmc_errs[obs]
            dev = (dv - hv) / (he + 1e-30)
            print(f"  {obs:>14s}: DM {dv:.4e}+/-{de:.1e}  HMC {hv:.4e}+/-{he:.1e}  z={dev:+.2f}")
        rows.append({
            "k": k_str, "n_kept": n_kept, "n_total": n_total,
            "dm_vals": dm_vals, "dm_errs": dm_errs,
            "hmc_vals": hmc_vals, "hmc_errs": hmc_errs,
        })

    out_dir = os.path.join(BASE, "runs", "_multiL_crossL_logs")
    os.makedirs(out_dir, exist_ok=True)

    txt_path = os.path.join(out_dir, "multiL_crossL_L128.txt")
    with open(txt_path, "w") as f:
        for r in rows:
            f.write(f"=== kappa = {r['k']}  N_kept={r['n_kept']}/{r['n_total']} ===\n")
            f.write(f"  {'obs':>14s}  {'DM':>22s}  {'HMC':>22s}  {'z=(DM-HMC)/dHMC':>14s}\n")
            for obs in ORDER:
                dv = r['dm_vals'][obs]; de = r['dm_errs'][obs]
                hv = r['hmc_vals'][obs]; he = r['hmc_errs'][obs]
                z = (dv - hv) / (he + 1e-30)
                f.write(f"  {obs:>14s}  {dv:>10.4e}+-{de:<9.1e}  {hv:>10.4e}+-{he:<9.1e}  {z:+14.2f}\n")
            f.write("\n")
    print(f"\nSaved {txt_path}")

    # LaTeX table
    lines = []
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Cross-$L$ generalisation of the 2D $\phi^4$ multi-$L$ diffusion models, trained on $L\in\{8,16,32,64\}$, $\lambda=0.022$ and tested at the held-out volume $L=128$. For each $\kappa$ the DM row gives $N=1024$ outlier-filtered, $Z_2$-symmetrised samples generated by reverse SDE integration ($2000$ EM steps, log time schedule); the HMC row is the reference ensemble at $L=128$ ($N=10240$). Errors are block-jackknife $1\sigma$ with $32$ blocks. Values quoted as $value(err)$ with the error in the last displayed digits.}")
    lines.append(r"\label{tab:multiL_crossL_2D_L128}")
    lines.append(r"\resizebox{\textwidth}{!}{%")
    lines.append(r"\begin{tabular}{llccccccccc}")
    lines.append(r"\toprule")
    hdr = " & ".join([TEX_NAMES[o] for o in ORDER])
    lines.append(rf"$\kappa$ & source & {hdr} \\")
    for i, r in enumerate(rows):
        lines.append(r"\midrule")
        # DM row
        dm_cells = [f"${fmt_err(r['dm_vals'][o], r['dm_errs'][o], sig_digits=1)}$" for o in ORDER]
        lines.append(rf"$\!\!{r['k']}\!\!$ & DM (multi-$L$) & " + " & ".join(dm_cells) + r" \\")
        # HMC row
        hmc_cells = [f"${fmt_err(r['hmc_vals'][o], r['hmc_errs'][o], sig_digits=1)}$" for o in ORDER]
        lines.append(r"& HMC & " + " & ".join(hmc_cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}%")
    lines.append(r"}")
    lines.append(r"\end{table*}")

    tex_path = os.path.join(out_dir, "multiL_crossL_L128.tex")
    with open(tex_path, "w") as f:
        # Replace ^{(s)} → ^{(\text{site})}
        out = "\n".join(lines)
        out = out.replace("^{(s)}", "^{(\\text{site})}")
        f.write(out + "\n")
    print(f"Saved {tex_path}")


if __name__ == "__main__":
    main()
