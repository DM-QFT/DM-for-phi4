using CUDA, Random, StochasticDiffEq

include("ModelB_fixed.jl")

const MODEL_B_SCIML_BASE = StochasticDiffEq.SciMLBase

"""Physical parameters carried by a `modelB_2d_fixed_problem`."""
struct ModelBFixedParameters
    γ::Float32
    T::Float32
    κ::Float32
    λ::Float32

    function ModelBFixedParameters(γ, T, κ, λ)
        γ, T, κ, λ = Float32.((γ, T, κ, λ))
        γ > 0.0f0 || throw(ArgumentError("γ must be positive"))
        T >= 0.0f0 || throw(ArgumentError("T must be nonnegative"))
        return new(γ, T, κ, λ)
    end
end

# This drift makes prob.f a useful representation of the deterministic part.
# The fixed solver itself calls the fused stage kernels in ModelB_fixed.jl.
function modelb_fixed_problem_drift_kernel!(
    du, u, two_kappa, m02, c3, inv_gamma,
    lattice, n,
)
    id = (blockIdx().x - Int32(1)) * blockDim().x + threadIdx().x
    stride = blockDim().x * gridDim().x
    @inbounds for linear in id:stride:n
        du[linear] = modelb_fixed_drift(
            u, linear, two_kappa, m02, c3, inv_gamma,
            lattice,
        )
    end
    return nothing
end

function modelb_fixed_problem_drift!(du, u, p::ModelBFixedParameters, t)
    check_modelb_fixed_state(u)
    lattice = Val(size(u, 1))
    inv_gamma = 1.0f0 / p.γ
    two_kappa = 2.0f0 * p.κ
    m02 = 2.0f0 * (1.0f0 - 2.0f0 * p.λ) - 8.0f0 * p.κ
    c3 = 4.0f0 * p.λ
    n = Int32(length(u))
    threads = 1024
    blocks = min(cld(length(u), threads), 264)
    @cuda threads=threads blocks=blocks modelb_fixed_problem_drift_kernel!(
        du, u, two_kappa, m02, c3, inv_gamma,
        lattice, n,
    )
    return nothing
end

function modelb_fixed_problem_diffusion!(du, u, p::ModelBFixedParameters, t)
    throw(ArgumentError(
        "modelB_2d_fixed_problem stores conserved link noise inside " *
        "ModelBFixedSOSRA; use solve(prob, ModelBFixedSOSRA()).",
    ))
end

"""
    modelB_2d_fixed_problem(u0; γ, tspan, T, κ, λ)

Build the dedicated SciML `SDEProblem` used by `ModelBFixedSOSRA`.  The state
must have shape `(L, L, Nensemble)`, where L is a power of two, and is copied
to a Float32 `CuArray`.
This problem is deliberately not compatible with generic SDE algorithms: its
spatially conserved link noise is generated by the specialized algorithm.
"""
function modelB_2d_fixed_problem(
    u0;
    γ=1.0f0,
    tspan=(0.0f0, 15.0f0),
    T=1.0f0,
    κ=0.2705f0,
    λ=0.022f0,
)
    u = CuArray{Float32}(u0)
    check_modelb_fixed_state(u)
    p = ModelBFixedParameters(γ, T, κ, λ)
    times = (Float32(tspan[1]), Float32(tspan[2]))
    times[2] >= times[1] || throw(ArgumentError("tspan must run forward"))
    return SDEProblem(
        modelb_fixed_problem_drift!, modelb_fixed_problem_diffusion!,
        u, times, p,
    )
end

"""
    ModelBFixedSOSRA(; buffers=nothing)

Fixed-step SciML algorithm backed by the fused GPU SOSRA implementation.
With the default `buffers=nothing`, each solve owns its buffers and is safe to
run independently.  Passing `modelb_fixed_buffers(prob.u0)` avoids repeated GPU
allocation, but that algorithm object must not be shared by concurrent solves.
"""
struct ModelBFixedSOSRA{B} <: MODEL_B_SCIML_BASE.AbstractSDEAlgorithm
    buffers::B
end

ModelBFixedSOSRA(; buffers=nothing) = ModelBFixedSOSRA(buffers)

MODEL_B_SCIML_BASE.isadaptive(::ModelBFixedSOSRA) = false
# Match SciML's SOSRA trait (weak order 2; strong order 1.5 for additive noise).
MODEL_B_SCIML_BASE.alg_order(::ModelBFixedSOSRA) = 2 // 1
MODEL_B_SCIML_BASE.requires_additive_noise(::ModelBFixedSOSRA) = true
MODEL_B_SCIML_BASE.allowscallback(::ModelBFixedSOSRA) = false
MODEL_B_SCIML_BASE.alg_interpretation(::ModelBFixedSOSRA) =
    MODEL_B_SCIML_BASE.AlgorithmInterpretation.Ito

function MODEL_B_SCIML_BASE.__solve(
    prob::MODEL_B_SCIML_BASE.SDEProblem,
    alg::ModelBFixedSOSRA;
    dt=0.002f0,
    adaptive=false,
    saveat=(),
    save_everystep=false,
    save_start=false,
    dense=false,
    maxiters=typemax(Int),
    seed=rand(UInt64),
    verbose=nothing,
)
    @assert prob.p isa ModelBFixedParameters
    check_modelb_fixed_state(prob.u0)
    @assert adaptive === false
    @assert dense === false
    @assert save_everystep === false
    if saveat != ()
        @assert saveat isa Number && Float32(saveat) == prob.tspan[2]
    end

    total_steps, dt = modelb_fixed_step_count(prob.tspan, dt)
    maxiters >= 0 || throw(ArgumentError("maxiters must be nonnegative"))
    run_steps = min(total_steps, Int(maxiters))
    seed = UInt64(seed)

    u = copy(prob.u0)
    buffers = if alg.buffers === nothing
        modelb_fixed_buffers(u; seed)
    else
        check_modelb_fixed_buffers(u, alg.buffers)
        CUDA.synchronize()
        seed_modelb_fixed!(alg.buffers, seed)
        alg.buffers
    end

    p = prob.p
    t0 = prob.tspan[1]
    relative_end = run_steps * dt
    t = run_steps == total_steps ? prob.tspan[2] : t0 + relative_end
    modelB_2d_fixed!(
        u, buffers;
        γ=p.γ, T=p.T, κ=p.κ, λ=p.λ,
        tspan=(0.0f0, relative_end), dt=dt,
    )
    CUDA.synchronize()

    ts = eltype(prob.tspan)[]
    us = typeof(u)[]
    if save_start && t != t0
        push!(ts, t0)
        push!(us, copy(prob.u0))
    end
    push!(ts, t)
    push!(us, u)

    stats = MODEL_B_SCIML_BASE.DEStats(0)
    stats.nf = 3 * run_steps
    stats.naccept = run_steps
    retcode = run_steps == total_steps ?
        MODEL_B_SCIML_BASE.ReturnCode.Success :
        MODEL_B_SCIML_BASE.ReturnCode.MaxIters
    interp = MODEL_B_SCIML_BASE.ConstantInterpolation(ts, us)
    return MODEL_B_SCIML_BASE.build_solution(
        prob, alg, ts, us;
        W=nothing,
        dense=false,
        interp=interp,
        calculate_error=false,
        timeseries_errors=false,
        retcode=retcode,
        stats=stats,
        seed=seed,
    )
end
